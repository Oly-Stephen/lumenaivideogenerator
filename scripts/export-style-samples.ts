// Exports one real keyframe per visual style (from completed live projects) to apps/web/public/styles/<style>.jpg,
// used as style thumbnails on the Create page. Styles without a real project keep their palette swatch.
//   node --env-file=.env --import tsx scripts/export-style-samples.ts
import { execFileSync } from "node:child_process";
import { mkdir, unlink, writeFile } from "node:fs/promises";
import ffmpegPath from "ffmpeg-static";
import pg from "pg";
import { r2ConfigFromEnv } from "../supabase/functions/_shared/r2.ts";
import { Storage } from "../apps/worker/src/storage.ts";

const db = new pg.Pool({ connectionString: process.env.DATABASE_URL!.replace(/\s+#.*$/, "").trim(), max: 1 });
const storage = new Storage(r2ConfigFromEnv((k) => process.env[k]));
const out = "apps/web/public/styles";
await mkdir(out, { recursive: true });

// Latest completed project per style whose scene-1 keyframe was generated by a real provider (not mock).
const { rows } = await db.query(`
  select distinct on (p.style_preset) p.style_preset, a.r2_key, a.bytes
  from projects p
  join scenes s on s.project_id = p.id and s.idx = 0
  join assets a on a.id = s.keyframe_asset_id
  where p.status = 'completed' and a.source like 'fal:%'
  order by p.style_preset, p.created_at desc`);

for (const r of rows) {
  const raw = `${out}/_${r.style_preset}.png`;
  await writeFile(raw, await storage.get(r.r2_key));
  execFileSync(ffmpegPath as unknown as string, ["-v", "error", "-y", "-i", raw, "-vf", "scale=360:-2", "-q:v", "4", `${out}/${r.style_preset}.jpg`]);
  await unlink(raw);
  console.log(`${r.style_preset}: exported`);
}
await db.end();
